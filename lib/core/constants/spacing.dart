/// Spacing scale used for consistent paddings and gaps across the UI.
///
/// Prefer these tokens over hard-coded numbers in widgets.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;

  /// Common page horizontal padding.
  static const double pageHorizontal = 16;

  /// Common page vertical padding.
  static const double pageVertical = 16;
}
